words = IDIOMS.split()
seen = set()
db = []
for w in words:
    if len(w) != 4:
        raise SystemExit(f"非四字成语: {w}")
    if w in seen:
        raise SystemExit(f"重复: {w}")
    seen.add(w)
    db.append({"w": w, "p": " ".join(lazy_pinyin(w))})

lines = ["/* 成语库：build-data.py 生成，勿手改 */", "var CHENGYU_DB = ["]
for item in db:
    lines.append(f'  {{ w: "{item["w"]}", p: "{item["p"]}" }},')
lines.append("];")
out = "\n".join(lines) + "\n"

with open(__file__.rsplit("/", 2)[0] + "/public/data.js", "w", encoding="utf-8") as f:
    f.write(out)
print(f"OK: {len(db)} idioms")
